""" Property definitions """

from __future__ import annotations

from dataclasses import dataclass

from .const import (
    UNIT_CLIME_HEATPUMP,
    UNIT_CLIME_TEMPCONFIG,
    UNIT_NODE,
    UNIT_NODECONFIGURATION,
    UNIT_TEMPHUMCONTROL,
    PdoType,
)


@dataclass
class Property:
    """Dataclass for a Property"""

    unit: int
    subunit: int
    property_id: int
    property_type: int


@dataclass
class PropertyConstraints:
    """The raw value of a numeric property, with the range and step size the unit accepts."""

    value: int
    minimum: int
    maximum: int
    step: int


