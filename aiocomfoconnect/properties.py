""" Property definitions """

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, Optional

from .const import (
    COMFOCLIME_AUTO_SEASON_MODES,
    COMFOCLIME_SEASONS,
    COMFOCLIME_TEMPERATURE_PROFILES,
    SENSOR_VENTILATION_MODES,
    TEMPERATURE_PROFILE_MODES,
    UNIT_CLIME_HEATPUMP,
    UNIT_CLIME_TEMPCONFIG,
    UNIT_NODE,
    UNIT_NODECONFIGURATION,
    UNIT_TEMPHUMCONTROL,
    UNIT_VENTILATIONCONFIG,
    PdoType,
    ProductId,
)


@dataclass
class Property:
    """Dataclass for a Property"""

    unit: int
    subunit: int
    property_id: int
    property_type: int
    product: Optional[int] = None  # The ProductId of the node it lives on, None for the ventilation unit (ComfoAir Q or Flex).
    options: Optional[Dict[int, str]] = None  # The option of each raw value, for properties that are an enum.


@dataclass
class PropertyConstraints:
    """The raw value of a numeric property, with the range and step size the unit accepts."""

    value: int
    minimum: int
    maximum: int
    step: int


